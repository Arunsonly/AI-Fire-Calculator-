-- AI Fire Calculator: initial Supabase schema
-- This schema stores tariff data but does NOT insert unverified tariff rows.
-- Run only after Supabase project exists and the tariff master has been checked.

create table if not exists public.tariff_occupancies (
  id bigint generated by default as identity primary key,
  occupancy_no integer not null unique,
  occupancy_description text not null,
  rate_upto_5cr_sookshma numeric(10,4),
  rate_5cr_to_50cr_laghu numeric(10,4),
  rate_above_50cr_sfsp numeric(10,4),
  stfi_rate numeric(10,4),
  source_document text not null default 'Oriental Fire Tariff Ready Reckoner effective 2021-04-01',
  verification_status text not null default 'needs_pdf_verification'
    check (verification_status in ('needs_pdf_verification','verified','manual_review_required')),
  source_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists tariff_occupancies_description_search_idx
  on public.tariff_occupancies using gin (to_tsvector('english', coalesce(occupancy_description, '')));

-- Keep public access disabled until a server-side API and admin authentication are configured.
alter table public.tariff_occupancies enable row level security;
