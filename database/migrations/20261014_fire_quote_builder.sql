-- Supabase schema additions for the fire quotation builder.
alter table public.tariff_occupancies add column if not exists section text;
alter table public.tariff_occupancies add column if not exists tac_code text;
alter table public.tariff_occupancies add column if not exists terrorism_rate numeric;

create table if not exists public.eq_rate_master (
 id bigint generated by default as identity primary key,
 state text not null,
 district text not null,
 eq_zone text,
 rate numeric not null,
 source text not null default 'Quote Calculator.xlsm',
 updated_at timestamptz not null default now(),
 unique(state,district)
);
alter table public.eq_rate_master enable row level security;
drop policy if exists "Public read EQ rate master" on public.eq_rate_master;
create policy "Public read EQ rate master" on public.eq_rate_master for select to anon, authenticated using (true);
grant select on public.eq_rate_master to anon, authenticated;

create table if not exists public.fire_quotations (
 id bigint generated by default as identity primary key,
 quote_no text unique,
 insured_name text not null,
 risk_address text,
 state text,
 district text,
 occupancy_no integer,
 occupancy_description text,
 tac_code text,
 tenure text,
 policy_type text,
 sum_insured numeric not null check (sum_insured > 0),
 floater text,
 basic_rate numeric,
 basic_discount_pct numeric default 0,
 stfi_rate numeric,
 eq_zone text,
 eq_rate numeric,
 terrorism_rate numeric,
 floater_rate numeric default 0,
 total_rate numeric,
 net_premium numeric,
 gst numeric,
 premium_with_gst numeric,
 total_discount numeric,
 calculation_snapshot jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);
alter table public.fire_quotations enable row level security;
drop policy if exists "Public can submit fire quotations" on public.fire_quotations;
create policy "Public can submit fire quotations" on public.fire_quotations for insert to anon, authenticated with check (length(trim(insured_name)) between 1 and 200 and sum_insured > 0);
grant insert on public.fire_quotations to anon, authenticated;
grant usage, select on sequence public.fire_quotations_id_seq to anon, authenticated;

